import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { launchApp } from '../fixtures/launch'
import { seedResearch, researchQuote, captureResearchViews, researchEvidenceDirectory } from '../fixtures/libraryResearch'
import { reopenEvidenceApp } from '../fixtures/libraryEvidence'
import { gotoModule } from '../helpers/nav'

test('十篇二十卡、问题选卡、素材排序/历史/选定更新、完整导出与重启', async () => {
  test.setTimeout(240_000)
  let fixture!: ReturnType<typeof seedResearch>
  const ctx = await launchApp({ executablePath: process.env.MIMIR_E2E_PACKAGED, transformSeed: seed => { fixture = seedResearch(seed); return fixture.seed } })
  let restarted: Awaited<ReturnType<typeof reopenEvidenceApp>> | undefined
  try {
    const { page } = ctx
    await gotoModule(page, 'library')
    await page.locator('button[title="合成研究课题"]').click()
    await page.getByRole('button', { name: '研究问题与写作素材', exact: true }).click()
    await page.getByRole('button', { name: '新建问题', exact: true }).click()
    await page.getByLabel('问题标题', { exact: true }).fill('真实界面建立的问题')
    await page.getByLabel('具体研究问题', { exact: true }).fill('  多行研究问题\n\n')
    await page.getByRole('button', { name: '选择证据', exact: true }).click()
    const picker = page.getByRole('dialog', { name: '选择已有证据', exact: true })
    await picker.getByLabel(`选择证据 ${fixture.cards[0]!.id}`, { exact: true }).check()
    await picker.getByRole('button', { name: '应用选择', exact: true }).click()
    await page.getByRole('button', { name: '保存问题', exact: true }).click()
    await expect(page.getByText('问题已保存', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '打开问题 合成问题组0', exact: true }).click()
    const comparison = page.getByRole('region', { name: '研究问题证据比较', exact: true })
    await expect(comparison.getByText('支持 5', { exact: true })).toBeVisible()
    await expect(comparison.getByText('反对 5', { exact: true })).toBeVisible()
    await expect(comparison.getByText('混合 5', { exact: true })).toBeVisible()
    await expect(comparison.getByText('未判断 5', { exact: true })).toBeVisible()
    await captureResearchViews(page, 'comparison')
    await page.getByRole('button', { name: '写作素材', exact: true }).click()
    await page.getByRole('button', { name: '新建素材包', exact: true }).click()
    await page.getByLabel('素材包标题', { exact: true }).fill('真实界面写作素材')
    await page.getByLabel('选入问题', { exact: true }).selectOption(fixture.questions[0]!.id)
    await page.getByRole('button', { name: '从问题组选入证据', exact: true }).click()
    await picker.getByLabel(`选择证据 ${fixture.cards[0]!.id}`, { exact: true }).check()
    await picker.getByLabel(`选择证据 ${fixture.cards[1]!.id}`, { exact: true }).check()
    await picker.getByRole('button', { name: '应用选择', exact: true }).click()
    await page.getByLabel('拟写小节 1', { exact: true }).fill('讨论')
    await page.getByLabel('拟写小节 2', { exact: true }).fill('结果')
    await page.getByRole('button', { name: '上移条目 2', exact: true }).click()
    await page.getByRole('button', { name: '保存素材包', exact: true }).click()
    await expect(page.getByText('素材包已保存，历史引用保留', { exact: true })).toBeVisible()
    const path = join(fixture.root, '.mimir/library/research.json'), doc = () => JSON.parse(readFileSync(path, 'utf8'))
    const saved = doc().packs.find((p: any) => p.versions[0].title === '真实界面写作素材')
    expect(saved.versions[0].items.map((i: any) => i.cardId)).toEqual([fixture.cards[1]!.id, fixture.cards[0]!.id])
    const pinned = saved.versions[0].items.find((i: any) => i.cardId === fixture.cards[0]!.id)
    await page.evaluate(async cardId => {
      const api = window.electronAPI!.libraryEvidence, r = await api.list({ filter: { archive: 'exclude', source: 'all' }, page: 1 })
      if (!r.ok) throw Error(r.message)
      const d = await api.detail({ scope: r.scope, cardId }); if (!d.ok) throw Error(d.message)
      const v = d.card.versions.at(-1)!, fields = Object.fromEntries(['paperId', 'projectIds', 'question', 'claim', 'quote', 'method', 'datasetOrMaterial', 'finding', 'limitation', 'comment', 'relation', 'locator'].map(k => [k, v[k as keyof typeof v]])) as any
      const updated = await api.update({ scope: r.scope, cardId, expectedRevision: d.revision, input: { ...fields, quote: fields.quote + '显式新证据版本' } })
      if (!updated.ok) throw Error(updated.message)
    }, fixture.cards[0]!.id)
    await page.getByRole('button', { name: '重新加载详情', exact: true }).click()
    await page.getByRole('region', { name: '固定版本素材', exact: true }).locator('details').nth(1).locator('summary').click()
    await expect(page.getByText('证据已有新版', { exact: false }).first()).toBeVisible()
    expect(doc().packs.find((p: any) => p.id === saved.id).versions[0]).toEqual(saved.versions[0])
    await page.getByRole('button', { name: '更新引用', exact: true }).click()
    const diff = page.getByRole('dialog', { name: '更新所选引用', exact: true })
    await diff.getByLabel(`选择更新 ${pinned.id}`, { exact: true }).check()
    await diff.getByRole('button', { name: '预览所选差异', exact: true }).click()
    await expect(diff.getByText('新版内容', { exact: true })).toBeVisible()
    expect(await diff.locator('pre').first().textContent()).toBe(researchQuote)
    await captureResearchViews(page, 'diff')
    await diff.getByRole('button', { name: '确认更新所选引用', exact: true }).click()
    await expect(diff).toBeHidden()
    expect(doc().packs.find((p: any) => p.id === saved.id).versions).toHaveLength(2)
    expect(doc().packs.find((p: any) => p.id === saved.id).versions[1].items.map((i: any) => i.evidenceVersion)).toEqual([1, 3])
    await page.getByRole('button', { name: '导出素材', exact: true }).click()
    const exportDialog = page.getByRole('dialog', { name: '导出写作素材', exact: true })
    await expect(exportDialog.getByRole('button', { name: '保存为新文件', exact: true })).toBeEnabled()
    const markdown = await exportDialog.locator('pre').textContent(), output = join(ctx.tempHome.root, 'research.md')
    expect(markdown).toContain('显式新证据版本')
    await captureResearchViews(page, 'export')
    await ctx.app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = (async () => ({ canceled: false, filePath })) as any }, output)
    await exportDialog.getByRole('button', { name: '保存为新文件', exact: true }).click()
    await expect(exportDialog.getByText('已保存为 research.md', { exact: true })).toBeVisible()
    expect(readFileSync(output, 'utf8')).toBe(markdown)
    await exportDialog.getByRole('button', { name: '关闭预览', exact: true }).click()
    await page.getByText('修订历史 · 旧版本只读', { exact: true }).click()
    await page.getByRole('button', { name: /^v1 ·/ }).click()
    await expect(page.getByLabel('素材包标题', { exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: '导出素材', exact: true }).click()
    await expect(exportDialog.getByRole('button', { name: '保存为新文件', exact: true })).toBeEnabled()
    expect(await exportDialog.locator('pre').textContent()).not.toContain('显式新证据版本')
    await exportDialog.getByRole('button', { name: '关闭预览', exact: true }).click()
    await page.getByRole('button', { name: /^v2 ·/ }).click()
    await expect(page.getByLabel('素材包标题', { exact: true })).toBeVisible()
    const visualDir = researchEvidenceDirectory()
    // 产品3项主题；跟随系统分别覆盖浅/深，组成4种实际呈现。
    for (const theme of ['light', 'dark', 'system-light', 'system-dark']) for (const width of [1280, 800]) {
      await page.emulateMedia({ colorScheme: theme.endsWith('dark') ? 'dark' : 'light' })
      await page.evaluate(dark => document.documentElement.classList.toggle('dark', dark), theme.endsWith('dark'))
      await page.setViewportSize({ width, height: 900 })
      await expect(page.getByRole('button', { name: '保存素材包', exact: true })).toBeVisible()
      await page.screenshot({ path: join(visualDir, `${process.env.MIMIR_E2E_PACKAGED ? 'package' : 'development'}-${theme}-${width}.png`) })
    }
    await page.getByLabel('素材包标题', { exact: true }).fill('超'.repeat(201))
    await page.getByRole('button', { name: '保存素材包', exact: true }).click()
    await expect(page.getByRole('alert')).toBeInViewport()
    await expect(page.getByLabel('素材包标题', { exact: true })).toHaveValue('超'.repeat(201))
    await captureResearchViews(page, 'error')
    await page.getByLabel('素材包标题', { exact: true }).fill('真实界面写作素材')
    await page.getByLabel('素材包说明', { exact: true }).fill('切换与原生关闭均须保留的输入')
    const leave = page.getByRole('dialog', { name: '存在未保存的研究资料编辑', exact: true })
    await page.getByLabel('素材包说明', { exact: true }).press('Escape')
    await leave.getByRole('button', { name: '留在这里', exact: true }).click()
    await expect(page.getByLabel('素材包说明', { exact: true })).toHaveValue('切换与原生关闭均须保留的输入')
    await page.getByRole('button', { name: '资产库', exact: true }).first().click()
    await leave.getByRole('button', { name: '留在这里', exact: true }).click()
    await page.locator('button[title="第二课题"]').click()
    await leave.getByRole('button', { name: '留在这里', exact: true }).click()
    await ctx.app.evaluate(({ BrowserWindow, dialog }) => { (globalThis as any).__researchClosePrompts = 0; dialog.showMessageBoxSync = (() => { (globalThis as any).__researchClosePrompts++; return 0 }) as any; BrowserWindow.getAllWindows()[0]!.close() })
    await expect.poll(() => ctx.app.evaluate(() => (globalThis as any).__researchClosePrompts)).toBe(1)
    await expect(page.getByLabel('素材包说明', { exact: true })).toHaveValue('切换与原生关闭均须保留的输入')
    await page.getByRole('button', { name: '取消编辑', exact: true }).click()
    await expect(page.getByRole('button', { name: '新建素材包', exact: true })).toBeFocused()
    await page.getByRole('button', { name: '打开素材包 真实界面写作素材', exact: true }).click()
    await expect(page.getByLabel('素材包标题', { exact: true })).toHaveValue('真实界面写作素材')
    const before = readFileSync(path)
    restarted = await reopenEvidenceApp(ctx)
    await gotoModule(restarted.page, 'library')
    const openResearch = restarted.page.getByRole('button', { name: '研究问题与写作素材', exact: true })
    if (await openResearch.isVisible()) await openResearch.click()
    await restarted.page.getByRole('button', { name: '写作素材', exact: true }).click()
    await restarted.page.getByRole('button', { name: '打开素材包 真实界面写作素材', exact: true }).click()
    await expect(restarted.page.getByLabel('素材包标题', { exact: true })).toHaveValue('真实界面写作素材')
    expect(readFileSync(path)).toEqual(before)
  } finally { try { await restarted?.app.close() } finally { await ctx.cleanup() } }
})
